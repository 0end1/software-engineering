#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""scaffold_project.py — 软件工程项目脚手架生成器

根据选定的开发模式，为新建软件项目生成标准化的目录骨架与初始工程文档，
将软件工程生命周期规范落地为可执行的工程结构。

用法:
    python3 scaffold_project.py --name <项目名> [--model <模式>] [--path <目录>] [--no-docs]

参数:
    --name    项目名称（必填），同时作为根目录名与包名
    --model   开发模式: waterfall | prototype | incremental | spiral | agile (默认 agile)
    --path    生成目标目录 (默认: ./<name>)
    --no-docs 不生成工程文档（仅目录骨架）

示例:
    python3 scaffold_project.py --name mstores --model agile
    python3 scaffold_project.py --name bank-core --model waterfall --path /tmp/proj
"""

import argparse
import os
import sys

MODELS = ["waterfall", "prototype", "incremental", "spiral", "agile"]

MODEL_DESC = {
    "waterfall": "瀑布模型：需求明确、变化少，顺序推进、文档齐全",
    "prototype": "原型模型：需求不明确，先快速做原型与用户确认",
    "incremental": "增量模型：按优先级分批交付可用功能",
    "spiral": "螺旋模型：大型高风险，风险驱动迭代",
    "agile": "敏捷开发：需求变化快，小步快跑持续交付",
}

# 各模式对应的目录骨架（相对项目根）
MODEL_LAYOUT = {
    "waterfall": {
        "docs": ["01-可行性研究", "02-需求分析", "03-概要设计",
                 "04-详细设计", "05-编码实现", "06-软件测试",
                 "07-部署", "08-维护"],
        "src": ["main"],
        "tests": ["unit", "integration"],
    },
    "prototype": {
        "docs": ["需求澄清", "正式需求"],
        "prototype": ["v1", "v2"],
        "src": ["main"],
        "tests": ["unit"],
    },
    "incremental": {
        "docs": ["架构设计", "增量规划"],
        "increments": ["inc-1-core", "inc-2-advanced"],
        "src": ["main"],
        "tests": ["unit", "integration", "regression"],
    },
    "spiral": {
        "docs": ["风险登记册"],
        "iterations": ["iter-1", "iter-2", "iter-3"],
        "prototype": ["risk-spike"],
        "src": ["main"],
        "tests": ["unit"],
    },
    "agile": {
        "docs": ["backlog"],
        "sprints": ["sprint-01", "sprint-02"],
        "src": ["main"],
        "tests": ["unit", "integration", "e2e"],
    },
}


def render_readme(name, model):
    return f"""# {name}

> 开发模式：**{model}** — {MODEL_DESC[model]}

本工程由软件工程技能（software-engineering）脚手架自动生成，遵循该模式的
生命周期节奏进行开发。详细执行细则见技能 `references/development-models.md`。

## 工程结构

{render_tree(name, model)}

## 当前模式工作流

- 模式：{model}
- 适用：{MODEL_DESC[model]}

请按该模式对应的阶段/迭代推进，并在各阶段产出对应文档（见 `docs/`）。

## 切换模式

如需在开发过程中切换模式，按软件工程技能的「模式切换矩阵」调整后续结构即可，
已有产出物（文档、代码、测试）应予以保留。

---
Generated by software-engineering skill · scaffold_project.py
"""


def render_tree(name, model):
    layout = MODEL_LAYOUT[model]
    lines = [name + "/"]
    for top in layout:
        lines.append(f"├── {top}/")
        for sub in layout[top]:
            lines.append(f"│   ├── {sub}/")
    lines.append("└── README.md")
    return "\n".join(lines)


