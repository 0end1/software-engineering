def main():
    parser = argparse.ArgumentParser(description="软件工程项目脚手架生成器")
    parser.add_argument("--name", required=True, help="项目名称")
    parser.add_argument("--model", default="agile", choices=MODELS,
                        help="开发模式 (默认 agile)")
    parser.add_argument("--path", default=None, help="生成目标目录 (默认 ./<name>)")
    parser.add_argument("--no-docs", action="store_true", help="仅生成目录骨架")
    args = parser.parse_args()

    root = args.path or os.path.join(os.getcwd(), args.name)
    if os.path.exists(root) and os.listdir(root):
        sys.exit(f"错误：目标目录已存在且非空: {root}")

    layout = MODEL_LAYOUT[args.model]
    created = []

    # 创建目录骨架
    for top, subs in layout.items():
        top_dir = os.path.join(root, top)
        os.makedirs(top_dir, exist_ok=True)
        created.append(top + "/")
        for sub in subs:
            sub_dir = os.path.join(top_dir, sub)
            os.makedirs(sub_dir, exist_ok=True)
            # 为每个子目录放置 .gitkeep，确保空目录纳入版本控制
            open(os.path.join(sub_dir, ".gitkeep"), "w").close()
            created.append(f"{top}/{sub}/")

    # 生成文档
    if not args.no_docs:
        docs = {
            "README.md": render_readme(args.name, args.model),
            os.path.join("docs", "SRS.md"): render_srs(args.name),
            os.path.join("docs", "design.md"): render_design(args.name, args.model),
            os.path.join("docs", "test-plan.md"): render_test_plan(args.name, args.model),
        }
        for rel, content in docs.items():
            full = os.path.join(root, rel)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as f:
                f.write(content)
            created.append(rel)

    # 生成 src 占位入口
    entry = os.path.join(root, "src", "main", "README.md")
    os.makedirs(os.path.dirname(entry), exist_ok=True)
    with open(entry, "w", encoding="utf-8") as f:
        f.write(f"# 源码入口 — {args.name}\n\n在此编写可维护、可复用的代码。\n")

    print(f"✅ 已生成项目骨架: {root}")
    print(f"   开发模式: {args.model} — {MODEL_DESC[args.model]}")
    print(f"   文件/目录数: {len(created)}")
    for c in created:
        print(f"   + {c}")


if __name__ == "__main__":
    main()
